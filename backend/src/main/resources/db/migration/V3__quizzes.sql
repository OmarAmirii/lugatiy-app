CREATE TABLE quiz_levels (
 id UUID PRIMARY KEY, name VARCHAR(120) NOT NULL UNIQUE, description TEXT NOT NULL DEFAULT '', difficulty INTEGER NOT NULL CHECK (difficulty BETWEEN 1 AND 10)
);
CREATE TABLE quizzes (
 id UUID PRIMARY KEY, level_id UUID NOT NULL REFERENCES quiz_levels(id), title VARCHAR(200) NOT NULL, description TEXT NOT NULL DEFAULT '', published BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE quiz_questions (
 id UUID PRIMARY KEY, quiz_id UUID NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE, prompt TEXT NOT NULL, position INTEGER NOT NULL, explanation TEXT NOT NULL DEFAULT '', UNIQUE(quiz_id, position)
);
CREATE TABLE quiz_answers (
 id UUID PRIMARY KEY, question_id UUID NOT NULL REFERENCES quiz_questions(id) ON DELETE CASCADE, answer_text TEXT NOT NULL, correct BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX quiz_one_correct_answer ON quiz_answers(question_id) WHERE correct;
CREATE TABLE quiz_attempts (
 id UUID PRIMARY KEY, quiz_id UUID NOT NULL REFERENCES quizzes(id), user_id UUID NOT NULL REFERENCES app_users(id), score INTEGER NOT NULL, total INTEGER NOT NULL, completed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX quiz_attempts_user_idx ON quiz_attempts(user_id, completed_at DESC);
